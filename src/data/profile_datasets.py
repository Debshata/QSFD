"""Generate the dataset analysis report for every available source.

Produces ``reports/dataset_summary.csv`` (machine-readable),
``data/metadata/dataset_specs.json`` (column roles per dataset) and
``reports/dataset_report.md`` (human-readable).
"""
from __future__ import annotations

import json
from typing import Any

import pandas as pd

from src.data.loaders import load_dataset
from src.data.registry import available_datasets
from src.data.validators import profile_dataset, validate_dataset
from src.utils.config import get_path
from src.utils.logging import get_logger

LOGGER = get_logger(__name__)

# Profiling reads the full file, so cap very large sources. The class balance
# of a stratified subsample is preserved, which is what the report is about.
PROFILE_MAX_ROWS = 500_000


def profile_all() -> tuple[pd.DataFrame, dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    details: dict[str, Any] = {}

    for name, rec in available_datasets().items():
        LOGGER.info("=== Profiling %s ===", name)
        try:
            loaded = load_dataset(name, rec["entry"], rec["file"],
                                  max_rows=PROFILE_MAX_ROWS)
            profile = profile_dataset(name, loaded.spec, loaded.X, loaded.y,
                                      loaded.n_rows_original)
            validation = validate_dataset(name, loaded.spec, loaded.X, loaded.y)
            profile["validation_passed"] = validation.passed
            profile["validation_errors"] = " | ".join(validation.errors)
            profile["validation_warnings"] = " | ".join(validation.warnings)
            rows.append(profile)
            details[name] = {
                "spec": loaded.spec.to_dict(),
                "profile": profile,
                "validation": validation.to_dict(),
            }
        except Exception as exc:  # noqa: BLE001 - one bad source must not stop the rest
            LOGGER.exception("Profiling failed for %s: %r", name, exc)
            details[name] = {"error": repr(exc)}

    df = pd.DataFrame(rows)
    return df, details


def write_markdown(df: pd.DataFrame, details: dict[str, Any], path) -> None:
    lines = [
        "# Dataset Analysis Report",
        "",
        "Generated by `python -m src.data.profile_datasets`.",
        "",
        f"Sources profiled: **{len(df)}**. Large files are stratified-subsampled "
        f"to {PROFILE_MAX_ROWS:,} rows for profiling; the fraud rate is preserved.",
        "",
        "## Summary",
        "",
        "| Dataset | Rows (file) | Rows profiled | Features | Target | Fraud | Fraud % | Missing | Duplicates |",
        "|---|---:|---:|---:|---|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| `{r['dataset']}` | {r['rows_in_source_file']:,} | {r['rows']:,} | "
            f"{r['n_numeric_features']}n + {r['n_categorical_features']}c | "
            f"`{r['target']}` | {r['fraud_count']:,} | {r['fraud_percentage']:.4f}% | "
            f"{r['missing_values']:,} | {r['duplicate_rows']:,} |"
        )

    lines += ["", "## Per-dataset detail", ""]
    for name, det in details.items():
        lines.append(f"### `{name}`")
        lines.append("")
        if "error" in det:
            lines += [f"**Profiling failed:** `{det['error']}`", ""]
            continue
        spec, prof, val = det["spec"], det["profile"], det["validation"]
        lines += [
            f"- **Source:** `{spec['kaggle_id']}` -> `{prof['file']}`",
            f"- **Description:** {spec['description'] or '(none)'}",
            f"- **Target:** `{spec['target']}` (1 = fraud)",
            f"- **Class balance:** {prof['fraud_count']:,} fraud vs "
            f"{prof['legitimate_count']:,} legitimate "
            f"({prof['fraud_percentage']:.4f}%, imbalance 1:{prof['imbalance_ratio']})",
            f"- **Chronological:** {spec['chronological']} "
            f"(time column: `{spec['time_column'] or 'none'}`)",
            f"- **Numeric features ({len(spec['numeric_features'])}):** "
            f"`{', '.join(spec['numeric_features'][:40]) or 'none'}`"
            + (" ..." if len(spec["numeric_features"]) > 40 else ""),
            f"- **Categorical features ({len(spec['categorical_features'])}):** "
            f"`{', '.join(spec['categorical_features']) or 'none'}`",
            f"- **Identifier columns excluded:** "
            f"`{', '.join(spec['identifier_features']) or 'none'}`",
            f"- **Potential-leakage columns excluded:** "
            f"`{', '.join(spec['potential_leakage_features']) or 'none'}`",
            f"- **Other excluded columns:** "
            f"`{', '.join(spec['unusable_features']) or 'none'}`",
            f"- **Missing values:** {prof['missing_values']:,} across "
            f"{prof['columns_with_missing']} columns",
            f"- **Duplicate rows:** {prof['duplicate_rows']:,} "
            f"({prof['duplicate_percentage']:.2f}%)",
            f"- **Validation:** {'PASSED' if val['passed'] else 'FAILED'}",
        ]
        for e in val["errors"]:
            lines.append(f"  - ERROR: {e}")
        for w in val["warnings"]:
            lines.append(f"  - warning: {w}")
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    reports = get_path("reports")
    metadata = get_path("data_metadata")

    df, details = profile_all()
    if df.empty:
        LOGGER.error("No datasets could be profiled")
        return 1

    csv_path = reports / "dataset_summary.csv"
    df.to_csv(csv_path, index=False)
    (metadata / "dataset_specs.json").write_text(
        json.dumps(details, indent=2, default=str), encoding="utf-8"
    )
    write_markdown(df, details, reports / "dataset_report.md")
    LOGGER.info("Dataset report written to %s", csv_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
